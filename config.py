def load_config(path=None, preset="main"):
    path = Path(path or __file__).expanduser().resolve()
    if path.suffix.lower() == ".json":
        return json.loads(path.read_text(encoding="utf-8"))
    if path.suffix.lower() != ".py":
        raise ValueError("Configuration must be a Python preset file or external JSON")
    namespace = globals() if path == Path(__file__).resolve() else runpy.run_path(str(path))
    if "CONFIG" in namespace:
        return deepcopy(namespace["CONFIG"])
    presets = namespace.get("PRESETS")
    if not isinstance(presets, dict) or preset not in presets:
        raise ValueError(f"Unknown configuration preset: {preset}")
    return deepcopy(presets[preset])
